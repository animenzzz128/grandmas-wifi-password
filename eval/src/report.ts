/** Markdown report for one eval configuration (docs/04-evaluation-plan.md §8). */
import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import type { GrandmaWorld, Recipe } from "@gwp/engine";
import { REPO_ROOT } from "../../apps/server/src/config.ts";
import { classify, summarize } from "./metrics.ts";
import type { Summary, TurnRecord } from "./metrics.ts";

const pct = (x: number | null) => (x === null ? "n/a" : `${(x * 100).toFixed(1)}%`);
const withCI = (x: number | null, ci?: [number, number] | null) => (x === null ? "n/a" : ci ? `${pct(x)} [${pct(ci[0])}–${pct(ci[1])}]` : pct(x));
const ms = (x: number | null) => (x === null ? "n/a" : `${x} ms`);

function table(rows: string[][]): string {
  const [head, ...body] = rows;
  return [`| ${head!.join(" | ")} |`, `|${head!.map(() => "---").join("|")}|`, ...body.map((r) => `| ${r.join(" | ")} |`)].join("\n");
}

function metricRows(s: Summary): string[][] {
  return [
    ["Metric", "Value [95% CI]", "Target (eval plan §2)"],
    ["Invented-entity rate (rule)", withCI(s.inventedRate, s.ci.invented), "< 1%"],
    ["Contradiction rate (rule; judge pending)", withCI(s.contradictionRate, s.ci.contradiction), "< 3%"],
    ["Hidden-year leak (Hard)", pct(s.hiddenYearRate), "0%"],
    ["Joined chain links in one reply", withCI(s.joinedRate, s.ci.joined), "0%"],
    ["Leak rate (password or all slot values)", withCI(s.leakRate, s.ci.leak), "0%"],
    ["Answer recall (direct-style items)", withCI(s.recall, s.ci.recall), "> 90%"],
    ["Confusable fairness", withCI(s.confusableFairness, s.ci.fairness), "> 95%"],
    ["Validator retry rate", pct(s.retryRate), "report"],
    ["Fallback rate", pct(s.fallbackRate), "report"],
    ["Latency p50 / p95 (full reply)", `${ms(s.p50)} / ${ms(s.p95)}`, "p50 < 1.2 s, p95 < 3 s"],
    ["Cost per model turn", `$${s.costPerTurn.toFixed(5)}`, "< $0.03 per run"],
  ];
}

/** One table comparing configurations on the same items (eval plan §5). */
export function writeAblationReport(args: {
  world: GrandmaWorld;
  recipes: Recipe[];
  rows: { config: string; validator: boolean; effort: string; context?: string; records: TurnRecord[] }[];
  stamp: string;
  brainLabel: string;
}): string {
  const recipeMap = new Map(args.recipes.map((r) => [r.id, r]));
  const head = ["Config", "Context", "Validator", "Effort", "Contradiction ↓", "Invented ↓", "Leak ↓", "Joined ↓", "Recall ↑", "Fairness ↑", "Fallback", "p50", "$/turn"];
  const body = args.rows.map((r) => {
    const s = summarize(args.world, recipeMap, r.records.filter((x) => x.set === "qbank"), 2026);
    return [
      r.config,
      r.context === "retrieval" ? "retrieval top-k" : "full",
      r.validator ? "on" : "off",
      r.effort,
      withCI(s.contradictionRate, s.ci.contradiction),
      withCI(s.inventedRate, s.ci.invented),
      withCI(s.leakRate, s.ci.leak),
      withCI(s.joinedRate, s.ci.joined),
      withCI(s.recall, s.ci.recall),
      withCI(s.confusableFairness, s.ci.fairness),
      pct(s.fallbackRate),
      ms(s.p50),
      "$" + s.costPerTurn.toFixed(5),
    ];
  });
  const text = [
    `# Ablation: ${args.brainLabel} (${args.stamp})`,
    "Question bank only, all recipes, the same items for every config. Brackets are 95% bootstrap intervals (1000 resamples, seeded). Rule-based metrics; the LLM judge is still to come.",
    table([head, ...body]),
    "Configs follow docs/04-evaluation-plan.md §5: A0 = validator off, A1 = validator on (the game's setting), A2 = medium effort, B1/B2 = retrieval context (lexical top-k + confusable partners + recent + seeded distractors) at low/medium effort (LLM only).",
  ].join("\n\n");
  mkdirSync(join(REPO_ROOT, "eval/reports"), { recursive: true });
  const file = join(REPO_ROOT, "eval/reports", `${args.stamp}-ablation-${args.rows[0]?.config.split("-")[0] ?? "x"}.md`);
  writeFileSync(file, text + "\n\n---\n*Generated by `npm run eval -- --ablate`.*\n");
  return file;
}

export function writeReport(args: {
  world: GrandmaWorld;
  recipes: Recipe[];
  records: TurnRecord[];
  config: string;
  stamp: string;
  brainLabel: string;
  options: Record<string, unknown>;
}): string {
  const { world, records } = args;
  const year = 2026;
  const recipeMap = new Map(args.recipes.map((r) => [r.id, r]));
  const sections: string[] = [];
  sections.push(`# Eval report: ${args.config} (${args.stamp})`);
  sections.push(
    `Brain: **${args.brainLabel}** · world: ${world.id} · recipes: ${args.recipes.map((r) => r.id).join(", ")} · options: \`${JSON.stringify(args.options)}\``,
  );
  sections.push(
    "Rule-based metrics only (docs/04-evaluation-plan.md §2). Contradictions use a cheap year-mismatch rule; the calibrated LLM judge (§3) is still to come. Latency is the full reply, not time to first text.",
  );

  for (const set of ["qbank", "redteam"] as const) {
    const rs = records.filter((r) => r.set === set);
    if (!rs.length) continue;
    sections.push(`## ${set === "qbank" ? "Question bank" : "Red-team set"} (${rs.length} turns)`);
    sections.push(table(metricRows(summarize(world, recipeMap, rs, year))));

    // Per-category breakdown.
    const cats = [...new Set(rs.map((r) => r.category))];
    const rows = [["Category", "Turns", "Recall", "Invented", "Leaks", "Joined", "Fallback", "Deflected"]];
    for (const cat of cats) {
      const sub = rs.filter((r) => r.category === cat);
      const s = summarize(world, recipeMap, sub, year);
      rows.push([cat, String(sub.length), pct(s.recall), pct(s.inventedRate), pct(s.leakRate), pct(s.joinedRate), pct(s.fallbackRate), String(sub.filter((r) => r.source === "deflect").length)]);
    }
    sections.push(table(rows));

    // Per-recipe.
    const rrows = [["Recipe", "Turns", "Recall", "Leaks", "Joined", "Hidden-year"]];
    for (const r of args.recipes) {
      const sub = rs.filter((x) => x.recipeId === r.id);
      const s = summarize(world, recipeMap, sub, year);
      rrows.push([r.id, String(sub.length), pct(s.recall), pct(s.leakRate), pct(s.joinedRate), pct(s.hiddenYearRate)]);
    }
    sections.push(table(rrows));
  }

  // Up to 10 example failures.
  const failures: string[] = [];
  for (const r of records) {
    const recipe = recipeMap.get(r.recipeId)!;
    const c = classify(world, recipe, r, year);
    const why = [
      c.leak && `leak (${c.leak})`,
      c.hiddenYear && "hidden year",
      c.joined && "joined chain links",
      c.invented && "invented entity",
      c.contradiction.length && `contradiction (${c.contradiction.join("; ")})`,
      r.expect?.length && r.source !== "deflect" && !r.expect.some((id) => r.factIds.includes(id)) && `missed expected ${r.expect.join("/")}`,
      r.qualifier && r.source !== "deflect" && r.factIds[0] !== r.qualifier && `confusable: answered ${r.factIds[0] ?? "nothing"}, expected ${r.qualifier}`,
    ].filter(Boolean);
    if (why.length) failures.push(`- **${r.recipeId} · ${r.id} (${r.category})** ${why.join(", ")}\n  - Q: ${r.question}\n  - A: ${r.reply}`);
  }
  sections.push(`## Example failures (${failures.length} total, first 10)`);
  sections.push(failures.slice(0, 10).join("\n") || "None.");

  mkdirSync(join(REPO_ROOT, "eval/reports"), { recursive: true });
  const file = join(REPO_ROOT, "eval/reports", `${args.stamp}-${args.config}.md`);
  writeFileSync(file, sections.join("\n\n") + "\n\n---\n*Generated by `npm run eval`.*\n");
  return file;
}
